# Dev-group tools (ruff/mypy/pytest/yamllint) that appear ONLY without
# `--no-dev`. The gate must never see these.
DEV_ONLY_NAMES = ("pytest", "ruff", "mypy", "respx", "yamllint", "pytest-asyncio")

# Hypothetical export where a RUNTIME dependency carries a copyleft license
# (the package name is what matters here; license is asserted via the gate).
RUNTIME_EXPORT_WITH_COPYLEFT = RUNTIME_EXPORT + """\
chardet==5.2.0
    # via nsg-mes-harness
"""


def _repo_root() -> Path:
    # tests/ -> linters/ -> tools/ -> repo root
    return Path(__file__).resolve().parents[3]


def _ci_yaml() -> str:
    return (_repo_root() / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# AC-1: gate is green when no runtime dependency is copyleft (current repo)
# ---------------------------------------------------------------------------


def test_ac1_runtime_set_has_no_forbidden_packages() -> None:
    # AC-1: License check is green for a repo whose runtime deps contain no
    # copyleft. The audited set is exactly the permissive runtime closure.
    packages = runtime_package_names(RUNTIME_EXPORT)
    assert "httpx" in packages
    assert "rich" in packages
    assert "pydantic" in packages
    assert "pydantic-settings" in packages
    # No dev-only tool leaked into the audited (runtime) set.
    assert all(name not in packages for name in DEV_ONLY_NAMES)


# ---------------------------------------------------------------------------
# AC-2: only runtime deps are audited; the dev dependency-group is excluded
# ---------------------------------------------------------------------------


def test_ac2_audited_command_scopes_to_runtime_packages_only() -> None:
    # AC-2: The license check audits ONLY runtime deps; the dev group is out of
    # scope. The pip-licenses command restricts the set via --packages.
    packages = runtime_package_names(RUNTIME_EXPORT)
    command = build_pip_licenses_command(packages)

    assert command[0] == "pip-licenses"
    assert "--packages" in command
    audited = command[command.index("--packages") + 1 :]
    assert audited == packages
    assert all(name not in audited for name in DEV_ONLY_NAMES)


def test_ac2_ci_step_syncs_and_runs_runtime_only() -> None:
    # AC-2: CI scopes the gate to runtime deps via --no-dev and the gate script.
    ci = _ci_yaml()
    assert "uv sync --no-dev --frozen" in ci
    assert "uv run --no-dev --with pip-licenses python tools/linters/license_gate.py" in ci


# ---------------------------------------------------------------------------
# AC-3: yamllint (GPL, dev-only) no longer fails the job and is not audited
# ---------------------------------------------------------------------------


def test_ac3_yamllint_excluded_from_audited_set() -> None:
    # AC-3: yamllint (GPL, dev-only) is not in the audited runtime set, so it
    # can no longer fail the job. It stays declared in [dependency-groups].dev.
    packages = runtime_package_names(RUNTIME_EXPORT)
    assert "yamllint" not in packages


def test_ac3_yamllint_still_declared_in_dev_group() -> None:
    # AC-3: yamllint is neither removed nor replaced; it remains a dev tool.
    pyproject = (_repo_root() / "pyproject.toml").read_text(encoding="utf-8")
    dev_section = pyproject.split("[dependency-groups]", 1)[1]
    assert "yamllint" in dev_section


# ---------------------------------------------------------------------------
# AC-4: a copyleft RUNTIME dependency still makes the gate fail
# ---------------------------------------------------------------------------


def test_ac4_copyleft_runtime_dependency_is_audited() -> None:
    # AC-4: If a copyleft dep is added to RUNTIME deps, it enters the audited
    # set and is therefore subject to --fail-on (job fails). Protection of the
    # distributed software is not weakened.
    packages = runtime_package_names(RUNTIME_EXPORT_WITH_COPYLEFT)
    assert "chardet" in packages

    command = build_pip_licenses_command(packages)
    audited = command[command.index("--packages") + 1 :]
    assert "chardet" in audited
    # The forbidden copyleft list is still applied to the audited set.
    assert "--fail-on" in command
    assert command[command.index("--fail-on") + 1] == build_fail_on()


# ---------------------------------------------------------------------------
# AC-5: the copyleft --fail-on list is unchanged; only the audited set narrows
# ---------------------------------------------------------------------------


def test_ac5_fail_on_list_is_unchanged() -> None:
    # AC-5: every AGPL/GPL/LGPL 3.0 variant (-only and -or-later) is preserved,
    # byte-for-byte identical to the historical pip-licenses --fail-on value.
    expected = (
        "AGPL-3.0;AGPL-3.0-only;AGPL-3.0-or-later;"
        "GPL-3.0;GPL-3.0-only;GPL-3.0-or-later;"
        "LGPL-3.0;LGPL-3.0-only;LGPL-3.0-or-later"
    )
    assert build_fail_on() == expected
    for family in ("AGPL-3.0", "GPL-3.0", "LGPL-3.0"):
        assert family in FORBIDDEN_LICENSES
        assert f"{family}-only" in FORBIDDEN_LICENSES
        assert f"{family}-or-later" in FORBIDDEN_LICENSES


def test_ac5_ci_step_does_not_inline_a_different_fail_on() -> None:
    # AC-5: the prohibited-license list lives in the gate module (single source
    # of truth); CI must not fork it by inlining the license list in a command.
    ci = _ci_yaml()
    assert build_fail_on() not in ci
    assert "AGPL-3.0;AGPL-3.0-only" not in ci


# ---------------------------------------------------------------------------
# AC-6: the CI step comment explains the runtime-only scope and why
