def test_ac6_ci_comment_explains_runtime_only_scope() -> None:
    # AC-6: the step comment documents that the gate audits runtime-only and
    # why (dev tools are not distributed).
    ci = _ci_yaml()
    assert "RUNTIME deps only" in ci
    assert "never distributed" in ci
    assert "yamllint" in ci


# ---------------------------------------------------------------------------
# Parser robustness
# ---------------------------------------------------------------------------


def test_runtime_package_names_ignores_comments_blank_and_option_lines() -> None:
    export = "# header\n\nhttpx==0.28.1\n-e file:./pkg\n   # via x\nrich==15.0.0\n"
    assert runtime_package_names(export) == ["httpx", "rich"]


def test_runtime_package_names_strips_extras_and_markers() -> None:
    export = "httpx[brotli]==0.28.1 ; python_version >= '3.12'\n"
    assert runtime_package_names(export) == ["httpx"]
